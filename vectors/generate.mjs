// Regenerates vectors/webhooks.json with node:crypto from the same inputs the server-side Swift tests use
// (backend Tests/AppTests/FluxTests/WaveD2TenantWebhookTests.swift, LBB server/Tests/AppTests/WaveB1WebhookSigTests.swift).
// Both the TypeScript tests and the Swift XCTests read the resulting file.
import { createHmac } from 'node:crypto'
import { writeFileSync } from 'node:fs'

const STRICT_B64 = /^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/
function key(secret) {
  const tail = secret.startsWith('whsec_') ? secret.slice(6) : secret
  return tail.length > 0 && STRICT_B64.test(tail) ? Buffer.from(tail, 'base64') : Buffer.from(secret, 'utf8')
}
const sign = (secret, id, ts, body) => 'v1,' + createHmac('sha256', key(secret)).update(`${id}.${ts}.${body}`).digest('base64')

