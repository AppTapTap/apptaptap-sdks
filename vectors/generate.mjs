const vectors = inputs.map(({ expect, ...v }) => {
  const signature = sign(v.secret, v.id, v.timestamp, v.body)
  if (expect && expect !== signature) throw new Error(`${v.name}: computed ${signature}, server test expects ${expect}`)
  if (v.secret.startsWith('whsec_') && /^[A-Za-z0-9]{32}$/.test(v.secret.slice(6)) && key(v.secret).length !== 24) throw new Error('bad key length')
  return { ...v, signature }
})
